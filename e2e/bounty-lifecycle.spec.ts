test('wallet pending state prevents duplicate writes and surfaces realm failures', async ({page,app}) => {
  await page.goto('/bounty/1'); await app.connect()
  let release!: () => void; app.txGate = new Promise<void>(resolve => release = resolve)
  const button = page.getByRole('button',{name:'Apply for this bounty'})
  try { await button.click(); await expect(page.getByRole('button',{name:'Sending application…'})).toBeDisabled(); expect(app.txs).toHaveLength(1) }
  finally { app.txGate = null; release() }
  await expect(page.getByRole('status')).toContainText('Application sent.')
  await page.goto('/bounty/2')
  app.nextTxError = 'A milestone is awaiting review.'
  await page.getByRole('button',{name:'Step back'}).click()
  await expect(page.getByRole('alert')).toContainText('A milestone is awaiting review.')
})

