test('worker delivers, reviewer requests changes, worker resubmits, reviewer releases payment', async ({page,app}) => {
  await page.goto('/bounty/2'); await app.connect()
  const first = page.getByRole('list',{name:'Milestones'}).getByRole('listitem').first()
  await first.getByRole('button',{name:'Submit work'}).click()
  await first.getByRole('textbox',{name:'Link to the work'}).fill('https://github.com/gnolang/gno/pull/100')
  await first.getByRole('button',{name:'Submit for review'}).click()
  await expect(first.getByText('In review',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Step back'})).toBeDisabled()
  expect(app.txs[0]!.messages[0]!.value.args).toEqual(['2','1','https://github.com/gnolang/gno/pull/100'])
  await app.setWallet(addresses.reviewer)
  await first.getByRole('button',{name:'Request changes',exact:true}).click()
  await first.getByRole('textbox',{name:'What needs to change'}).fill('Add keyboard navigation.')
  await first.locator('form').getByRole('button',{name:'Request changes',exact:true}).click()
  await expect(first.getByText('Changes requested:',{exact:true})).toBeVisible()
  await app.setWallet(addresses.worker)
  await first.getByRole('button',{name:'Resubmit work'}).click()
  await first.getByRole('textbox',{name:'Link to the work'}).fill('https://github.com/gnolang/gno/pull/101')
  await first.getByRole('button',{name:'Submit for review'}).click()
  await app.setWallet(addresses.reviewer)
  await first.getByRole('button',{name:'Approve',exact:true}).click()
  await expect(first.getByText('Paid',{exact:true})).toBeVisible()
  expect(app.txs.map(t => t.messages[0]!.value.func)).toEqual(['Submit','RequestChanges','Submit','Approve'])
  expect(app.get(2).paidOut).toBe(50_000_000)
})

