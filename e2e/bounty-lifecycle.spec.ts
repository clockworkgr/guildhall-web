import { test, expect, addresses } from './fixtures'

test('contributor applies and the poster assigns the applicant', async ({page,app}) => {
  await page.goto('/bounty/1'); await app.connect()
  await page.getByRole('textbox',{name:'Why you'}).fill('I can build an accessible explorer.')
  await page.getByRole('button',{name:'Apply for this bounty'}).click()
  await expect(page.getByRole('status')).toContainText('Application sent')
  await expect(page.getByText('You applied. The poster will assign someone.',{exact:true})).toBeVisible()
  expect(app.txs[0]!.messages[0]!.value).toMatchObject({func:'Apply',args:['1','I can build an accessible explorer.'],caller:addresses.worker})
  await app.setWallet(addresses.poster)
  await expect(page.getByRole('textbox',{name:"Contributor's address"})).toBeVisible()
  const application = page.locator('li').filter({hasText:'I can build an accessible explorer.'}).filter({has:page.getByRole('button',{name:'Assign',exact:true})})
  await application.getByRole('button',{name:'Assign',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Assigned.')
  expect(app.txs[1]!.messages[0]!.value).toMatchObject({func:'Assign',args:['1',addresses.worker]})
  await expect(page.getByText('In progress',{exact:true})).toBeVisible()
})

