test('board status and tag filters survive browser history', async ({page, app}) => {
  await page.goto('/bounties')
  const filters = page.getByRole('navigation', {name:'Filter by status'})
  await filters.getByRole('button', {name:'In progress',exact:true}).click()
  await expect(page.getByRole('list', {name:'Bounties'})).toContainText('Write the interrealm guide')
  await page.getByRole('textbox', {name:'Filter by tag'}).fill('#DOCS')
  await page.getByRole('button', {name:'Filter',exact:true}).click()
  await expect(page).toHaveURL(/status=active&tag=docs/)
  await expect(page.getByRole('list', {name:'Bounties'}).getByRole('listitem')).toHaveCount(2)
  await filters.getByRole('button', {name:'Completed',exact:true}).click()
  await expect(page.getByRole('heading', {name:'No bounties found'})).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('textbox', {name:'Filter by tag'})).toHaveValue('docs')
  await expect(page.getByRole('list', {name:'Bounties'}).getByRole('listitem')).toHaveCount(2)
  await page.getByRole('button', {name:'Clear filter'}).click()
  await expect(page.getByRole('textbox', {name:'Filter by tag'})).toHaveValue('')
  await expect(page.getByRole('list', {name:'Bounties'}).getByRole('listitem')).toHaveCount(4)
  expect(app.queries.some(q => q.includes('status=active&tag=docs'))).toBeTruthy()
})

test('board paginates, resets page on filtering, and normalizes invalid parameters', async ({page, app}) => {
  app.bounties = Array.from({length:25}, (_, i) => bounty(i + 10))
  await page.goto('/bounties?status=unknown&page=-3')
  await expect(page.getByRole('navigation', {name:'Filter by status'}).getByRole('button',{name:'Open',exact:true})).toHaveAttribute('aria-current','page')
  await expect(page.getByRole('list', {name:'Bounties'}).getByRole('listitem')).toHaveCount(20)
  await expect(page.getByRole('button', {name:'Newer'})).toBeDisabled()
  await page.getByRole('button', {name:'Older'}).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(page.getByRole('list', {name:'Bounties'}).getByRole('listitem')).toHaveCount(5)
  await expect(page.getByRole('button', {name:'Older'})).toBeDisabled()
  await page.getByRole('button', {name:'Newer'}).click()
  await expect(page.getByRole('list', {name:'Bounties'}).getByRole('listitem')).toHaveCount(20)
  await page.getByRole('button', {name:'Older'}).click()
  await page.getByRole('textbox', {name:'Filter by tag'}).fill('docs')
  await page.getByRole('button', {name:'Filter',exact:true}).click()
  await expect(page).not.toHaveURL(/page=/)
  await expect(page.getByRole('list', {name:'Bounties'}).getByRole('listitem')).toHaveCount(13)
})

