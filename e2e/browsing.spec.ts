test('profile address copying reports success and clipboard failures', async ({page,app}) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async (text:string) => { (window as any).__copied = text }}})
  })
  await page.goto(`/u/${addresses.worker}`)
  await page.getByRole('button',{name:'Copy address'}).click()
  await expect(page.getByRole('status')).toHaveText('Address copied')
  expect(await page.evaluate(() => (window as any).__copied)).toBe(addresses.worker)
  await page.evaluate(() => { Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async () => {throw new Error('No clipboard permission')}}}) })
  await page.getByRole('button',{name:'Address copied'}).click()
  await expect(page.getByRole('alert')).toContainText('Could not copy')
  expect(app.txs).toHaveLength(0)
})
